def _special(k, s):
    if k == "cashews-spicy-or-other":
        return "cashews-spicy" if "cashew" in s else ("peanuts-flavored" if "peanut" in s else ("almonds-flavored" if "almond" in s else ("pistachios" if "pistachio" in s else None)))
    if k == "cashews-seasoned-or-plain":
        return "cashews" if re.search(r"\bsalted|unsalted|medium", s) else "cashews-seasoned"
    return k

def key_for(name, sub, cat):
    rules = RULES.get(cat, [])
    for text in (name.lower(), f"{name} | {sub}".lower()):
        for rx, k in rules:
            if re.search(rx, text):
                r = _special(k, text)
                if r: return r
    return FALLBACK.get(cat, "misc")
