// Phone click-through: sign toggle → menu tab → item sheet options → quick add → builder → offer → bag → details → review → WhatsApp hand-off.
// usage: node flow.mjs <url> <outDir> <lang en|ar> [w h]
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
const [url, out, lang = 'en', w = 390, h = 844] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } : undefined });
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, isMobile: +w < 700, hasTouch: +w < 700, permissions: ['clipboard-read', 'clipboard-write'] });
const p = await ctx.newPage(); const errs = []; let n = 0;
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.addInitScript(() => { window.open = u => { window.__opened = u; return null; }; });
const shot = async name => { await p.waitForTimeout(900); await p.screenshot({ path: `${out}/${String(++n).padStart(2, '0')}_${name}.png` }); };
await p.goto(`${url}?nointro&lang=${lang}`, { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
await p.click('#wallsign'); await shot('sign_off');
await p.click('#wallsign'); await p.waitForTimeout(800);
await p.evaluate(() => document.getElementById('menu').scrollIntoView()); await p.waitForTimeout(500);
await p.click('.tab[data-c="offers"]'); await shot('tab_offers');
await p.click('.tab[data-c="burgers"]'); await p.waitForTimeout(500);
await p.click('.card[data-id="cheese"] .tx h3'); await shot('sheet_cheese');
await p.click('[data-prot="1"]'); await p.click('[data-rm="pickles"]'); await p.click('[data-ad="mozz"]'); await p.click('[data-sauce="garlic"]'); await p.click('#iplus');
await shot('sheet_opts');
await p.click('#iadd'); await p.waitForTimeout(300); await shot('fly_toast');
await p.click('.card[data-id="lebanese"] [data-quick]'); await p.waitForTimeout(900);
await p.evaluate(() => document.getElementById('build').scrollIntoView()); await p.waitForTimeout(600);
await p.click('.base[data-id="chili"]'); await p.waitForTimeout(700);
await p.click('#ctrls [data-k="patty"][data-v="1"]'); await p.click('#ctrls [data-k="mozz"]'); await p.click('#ctrls [data-k="cheddar"]');
await p.waitForTimeout(160); await p.screenshot({ path: `${out}/${String(++n).padStart(2, '0')}_builder_dropping.png` });
await shot('builder_done');
await p.click('#badd'); await p.waitForTimeout(1000);
await p.evaluate(() => document.getElementById('line').scrollIntoView()); await p.waitForTimeout(800);
await shot('reels');
await p.click('[data-offer]'); await p.waitForTimeout(1000);
await p.click('#sbag'); await shot('bag');
await p.click('#bnext'); await shot('details_empty');
await p.click('#bnext'); await shot('details_errors');
await p.fill('#f-name', lang === 'ar' ? 'علي' : 'Ali'); await p.fill('#f-phone', '71 123 456');
await p.click('[data-f="branch"][data-v="mcharafieh"]'); await p.waitForTimeout(300);
await p.fill('#f-addr', lang === 'ar' ? 'المشرفية، بناية الأمل، الطابق ٣' : 'Mcharafieh, Al Amal building, 3rd floor');
await p.click('[data-f="pay"][data-v="lbp"]'); await shot('details_filled');
await p.click('#bnext'); await shot('review');
await p.click('#bsend'); await shot('done');
const res = await p.evaluate(() => ({ opened: window.__opened, order: window.__lastOrder && window.__lastOrder.msg, cart: localStorage.getItem('tikiz.cart.v1'), badge: document.getElementById('bagn').textContent, dir: document.documentElement.dir }));
console.log(JSON.stringify(res, null, 1));
console.log('decoded wa text:\n' + decodeURIComponent((res.opened || '').split('text=')[1] || ''));
await p.evaluate(() => document.querySelector('.scrim').click()); await p.waitForTimeout(500);
await p.evaluate(() => document.getElementById('menu').scrollIntoView()); await p.waitForTimeout(400);
await p.click('.card[data-id="tikiz"] [data-quick]'); await p.waitForTimeout(1200);
await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(800);
console.log('after reload badge:', await p.evaluate(() => document.getElementById('bagn').textContent), 'lang kept:', await p.evaluate(() => document.documentElement.lang));
console.log('errors:', errs.length ? errs : 'none');
await b.close();
